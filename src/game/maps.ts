function parseMap(
  id: string,
  name: string,
  mode: ModeId,
  rows: string[],
  mirror: boolean
): GameMap {
  const h = rows.length
  const halfW = rows[0].length
  const w = mirror ? halfW * 2 : halfW
  const tiles = new Uint8Array(w * h)
  const spawns: GameMap['spawns'] = []
  const safes: GameMap['safes'] = []
  const boxes: Vec[] = []
  let mine: Vec | null = null
  let mineSum = v()
  let mineCount = 0

  const setTile = (tx: number, ty: number, ch: string, teamMirror: 0 | 1 | 2 | -1) => {
    const idx = ty * w + tx
    switch (ch) {
      case '#': tiles[idx] = T_WALL; break
      case '~': tiles[idx] = T_WATER; break
      case 'B': tiles[idx] = T_BUSH; break
      case 'C':
        boxes.push(v(tx + 0.5, ty + 0.5))
        break
      case 'M':
        mineSum = { x: mineSum.x + tx + 0.5, y: mineSum.y + ty + 0.5 }
        mineCount++
        break
      case 'a': case 'b': case 'c':
        spawns.push({ team: 0, pos: v(tx + 0.5, ty + 0.5) })
        break
      case 'x': case 'y': case 'z':
        spawns.push({ team: 1, pos: v(tx + 0.5, ty + 0.5) })
        break
      case 's':
        spawns.push({ team: 2, pos: v(tx + 0.5, ty + 0.5) })
        break
      case 'A':
        safes.push({ team: 0, pos: v(tx + 0.5, ty + 0.5) })
        break
      case 'Z':
        safes.push({ team: 1, pos: v(tx + 0.5, ty + 0.5) })
        break
      default:
        break
    }
  }

  const mirrorCh = (ch: string): string => {
    switch (ch) {
      case 'a': return 'x'
      case 'b': return 'y'
      case 'c': return 'z'
      case 'A': return 'Z'
      default: return ch
    }
  }

  for (let y = 0; y < h; y++) {
    const row = (rows[y] ?? '').padEnd(halfW, '.')
    for (let x = 0; x < halfW; x++) {
      setTile(x, y, row[x], -1)
    }
    if (mirror) {
      for (let x = 0; x < halfW; x++) {
        const ch = mirrorCh(row[x])
        setTile(w - 1 - x, y, ch, -1)
      }
    }
  }

  if (mineCount > 0) mine = { x: mineSum.x / mineCount, y: mineSum.y / mineCount }

  return { id, name, mode, w, h, tiles, mine, boxes, spawns, safes }
}

export const MAPS: GameMap[] = [
  parseMap('gem_grotto', 'Gem Grotto', 'gem', GEM_ROWS, true),
  parseMap('deadline', 'Deadline', 'bounty', BOUNTY_ROWS, true),
  parseMap('heist_hideout', 'Heist Hideout', 'heist', HEIST_ROWS, true),
  parseMap('skull_pit', 'Skull Pit', 'showdown', SHOWDOWN_ROWS, false),
]

export const mapById = (id: string): GameMap => MAPS.find((m) => m.id === id) ?? MAPS[0]

export const tileAt = (map: GameMap, tx: number, ty: number): number => {
  if (tx < 0 || ty < 0 || tx >= map.w || ty >= map.h) return T_WALL
  return map.tiles[ty * map.w + tx]
}

export const solidTile = (t: number) => t === T_WALL || t === T_WATER
export const blocksBullet = (t: number) => t === T_WALL
